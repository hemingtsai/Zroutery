#!/usr/bin/env python3
"""Render docs/development/current-state.md from state.json.

The state file is the machine-readable fact set; this renderer is the only
writer of the Markdown. Hand-editing the Markdown is a bug: CI compares the
committed rendering with a fresh one.

Usage:
    python3 -B scripts/current_state.py --write
    python3 -B scripts/current_state.py --check
"""

from __future__ import annotations

import argparse
import contextlib
import io
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATE = Path("docs/development/state.json")
TARGET = Path("docs/development/current-state.md")

HEADER = "<!-- generated by scripts/current_state.py; do not edit -->"


def render(state: dict) -> str:
    lines = [
        HEADER,
        "",
        "# Current state",
        "",
        f"as of `{state.get('as_of', 'unknown')}` · branch `{state.get('branch', 'unknown')}` · verified code head `{state.get('head', 'unknown')}`",
        "",
        "## Gates",
        "",
        "| Gate | Status | Source | Command | Detail |",
        "|---|---|---|---|---|",
    ]
    for gate in state.get("gates", []):
        detail = gate.get("detail", "")
        quarantine = gate.get("quarantine")
        if quarantine:
            note = f"quarantined by {quarantine.get('owner', '?')} until {quarantine.get('review_by', '?')}"
            detail = f"{detail} ({note})" if detail else note
        lines.append(
            "| {name} | **{status}** | {source} | `{command}` | {detail} |".format(
                name=gate.get("name", "?"),
                status=gate.get("status", "unknown"),
                source=gate.get("source", "unknown"),
                command=gate.get("command", ""),
                detail=detail,
            )
        )
    lines += ["", "## Blockers", ""]
    blockers = state.get("blockers", [])
    if blockers:
        for blocker in blockers:
            identifier = blocker.get("id", "?")
            summary = blocker.get("summary", "")
            status = blocker.get("status", "unknown")
            blocked_by = blocker.get("blocked_by") or []
            blocked = f"; blocked by {', '.join(blocked_by)}" if blocked_by else ""
            owner = f"; owner {blocker['owner']}" if blocker.get("owner") else ""
            ref = f"; ref {blocker['ref']}" if blocker.get("ref") else ""
            lines.append(f"- {identifier} {summary}: {status.upper()}{blocked}{owner}{ref}")
    else:
        lines.append("None.")
    lines += ["", "## Known flaky", ""]
    flaky = state.get("flaky", [])
    if flaky:
        lines += [
            f"- {item.get('name', '?')}: {item.get('reason', '')} (owner {item.get('owner', '?')}, review by {item.get('review_by', '?')})"
            for item in flaky
        ]
    else:
        lines.append("None.")
    lines += ["", "## Last full green", ""]
    green = state.get("last_full_green")
    lines.append(f"`{green}`" if green else "Not recorded. A green unit-test run is not a full green: Tier 2 gates are listed in `verification.md`.")
    return "\n".join(lines) + "\n"


def load_state(root: Path) -> dict:
    path = root / STATE
    return json.loads(path.read_text(encoding="utf-8"))


def self_test() -> int:
    import tempfile

    with tempfile.TemporaryDirectory(prefix="zr-state-") as temporary:
        root = Path(temporary)
        (root / STATE).parent.mkdir(parents=True)
        state = {
            "as_of": "2026-11-14",
            "branch": "test",
            "head": "abc1234",
            "gates": [{"name": "demo", "status": "pass", "command": "true", "detail": "ok"}],
            "blockers": [],
            "flaky": [],
            "last_full_green": None,
        }
        (root / STATE).write_text(json.dumps(state), encoding="utf-8")
        if main(["--root", str(root), "--write"]) != 0:
            print("current-state self-test: write failed", file=sys.stderr)
            return 1
        if main(["--root", str(root), "--check"]) != 0:
            print("current-state self-test: fresh render rejected", file=sys.stderr)
            return 1
        target = root / TARGET
        target.write_text(target.read_text(encoding="utf-8") + "hand edit\n", encoding="utf-8")
        # The stale message is the expected rejection; keep it out of the parent
        # gate's stderr, where it reads like a real failure.
        with contextlib.redirect_stderr(io.StringIO()):
            caught = main(["--root", str(root), "--check"]) != 0
        if not caught:
            print("current-state self-test: hand edit was NOT caught", file=sys.stderr)
            return 1
        print("current-state: self-test passed (writes, accepts its render, rejects a hand edit)")
        return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=str(ROOT))
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args(argv)
    if args.self_test:
        return self_test()
    root = Path(args.root)
    try:
        state = load_state(root)
    except (OSError, json.JSONDecodeError) as error:
        print(f"current-state: cannot read {STATE}: {error}", file=sys.stderr)
        return 2
    expected = render(state)
    target = root / TARGET
    if args.check:
        try:
            actual = target.read_text(encoding="utf-8")
        except OSError as error:
            print(f"current-state: cannot read {TARGET}: {error}", file=sys.stderr)
            return 1
        if actual != expected:
            print(f"current-state: {TARGET} is stale; run `python3 -B scripts/current_state.py --write`", file=sys.stderr)
            return 1
        print("current-state: clean")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(expected, encoding="utf-8")
    print(f"current-state: wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
