#!/usr/bin/env python3
"""Render docs/development/current-state.md from state.json.

The state file is the machine-readable fact set; this renderer is the only
writer of the Markdown. Hand-editing the Markdown is a bug: CI compares the
committed rendering with a fresh one.

Usage:
    python3 -B scripts/current_state.py --write
    python3 -B scripts/current_state.py --check
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATE = Path("docs/development/state.json")
TARGET = Path("docs/development/current-state.md")

HEADER = "<!-- generated by scripts/current_state.py; do not edit -->"


def render(state: dict) -> str:
    lines = [
        HEADER,
        "",
        "# Current state",
        "",
        f"as of `{state.get('as_of', 'unknown')}` · branch `{state.get('branch', 'unknown')}` · verified code head `{state.get('head', 'unknown')}`",
        "",
        "## Gates",
        "",
        "| Gate | Status | Command | Detail |",
        "|---|---|---|---|",
    ]
    for gate in state.get("gates", []):
        lines.append(
            "| {name} | **{status}** | `{command}` | {detail} |".format(
                name=gate.get("name", "?"),
                status=gate.get("status", "unknown"),
                command=gate.get("command", ""),
                detail=gate.get("detail", ""),
            )
        )
    lines += ["", "## Open issues", ""]
    issues = state.get("issues", [])
    if issues:
        for issue in issues:
            lines.append(f"- #{issue.get('number')} — {issue.get('title', '')}")
    else:
        lines.append("None recorded in this snapshot. Findings belong in GitHub Issues; this file links them, it does not copy them.")
    lines += ["", "## Blockers", ""]
    blockers = state.get("blockers", [])
    lines += [f"- {item}" for item in blockers] if blockers else ["None."]
    lines += ["", "## Known flaky", ""]
    flaky = state.get("flaky", [])
    lines += [f"- {item}" for item in flaky] if flaky else ["None."]
    lines += ["", "## Last full green", ""]
    green = state.get("last_full_green")
    lines.append(f"`{green}`" if green else "Not recorded. A green unit-test run is not a full green: Tier 2 gates are listed in `verification.md`.")
    return "\n".join(lines) + "\n"


def load_state(root: Path) -> dict:
    path = root / STATE
    return json.loads(path.read_text(encoding="utf-8"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=str(ROOT))
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    root = Path(args.root)
    try:
        state = load_state(root)
    except (OSError, json.JSONDecodeError) as error:
        print(f"current-state: cannot read {STATE}: {error}", file=sys.stderr)
        return 2
    expected = render(state)
    target = root / TARGET
    if args.check:
        try:
            actual = target.read_text(encoding="utf-8")
        except OSError as error:
            print(f"current-state: cannot read {TARGET}: {error}", file=sys.stderr)
            return 1
        if actual != expected:
            print(f"current-state: {TARGET} is stale; run `python3 -B scripts/current_state.py --write`", file=sys.stderr)
            return 1
        print("current-state: clean")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(expected, encoding="utf-8")
    print(f"current-state: wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
