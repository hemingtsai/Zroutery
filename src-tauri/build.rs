//! Build script for the desktop shell.
//!
//! The ACL is the point of the call below, not a formality. A Tauri
//! application's own `#[tauri::command]`s are *not* part of the permission
//! system until the application declares an app manifest: without one,
//! `RuntimeAuthority::has_app_manifest` is false and every command the webview
//! names is served from any local origin. Declaring the command list turns each
//! one into an `allow-<command>` permission (with `_` written as `-`, so
//! `get_snapshot` is `allow-get-snapshot`), and `capabilities/default.json`
//! grants them one at a time. From then on a command that is registered but not
//! granted is refused at the IPC boundary instead of quietly running.
//!
//! The list must stay equal to the `generate_handler!` list in `src/lib.rs`, and
//! nothing in Cargo connects the two. `scripts/command_surface_test.py` does: it
//! reads both, fails when they differ, and fails when a registered command has
//! no grant in the capability file.
//!
//! `permissions/autogenerated/` is where `tauri-build` writes the generated
//! permission files, so it is ignored rather than tracked — see `.gitignore`.

fn main() {
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(APP_COMMANDS)),
    )
    .expect("tauri-build failed");
}

